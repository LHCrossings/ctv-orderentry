"""Undo the 2026-09-29 Daviselen traffic mis-assignment on IG Pechanga 31500 (3133).

The Toyota Mandarin creative 148842 (TYRL6705TH) was written onto all 39 Pechanga spots
dated 10/01-10/25 and added to the four line pools. Restore each line to what its own
description names (Lee 9/30: "the description tells you what spot to run"):

  84746  Filipino 4p-6p [TM0701]      -> 146119 (PECHANGA30E140), as its 10/27-10/29 spots
  84747  Filipino 4p-6p [SC1115]      -> unassigned (SC1115 not ingested), as its 10/28 spot
  84748  BNS Filipino 4p-7p [SC1115]  -> unassigned
  84749  BNS Filipino 4p-7p [GL1211]  -> unassigned (GL1211 not ingested), as its 10/26+ spots

Dry run by default (rollback). --apply commits and re-reads from a fresh connection.
"""

import argparse
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from browser_automation.etere_direct_client import connect  # noqa: E402

CONTRACT = 3133
BAD_FILMATI = 148842
TM0701 = 146119
LINE_TM0701 = 84746
LINES_UNASSIGNED = {
    84747: "Filipino 4p-6p [SC1115]",
    84748: "BNS Filipino 4p-7p [SC1115]",
    84749: "BNS Filipino 4p-7p [GL1211]",
}
POOL_ROWS = (633673, 633674, 633675, 633676)  # CONTRATTIFILMATI ids for 148842 on the 4 lines
ORACLE_TM0701_TP = 15957189  # 84746 10/27 spot, untouched, carries 146119
ORACLE_UNASSIGNED_TP = 15957176  # 84747 10/28 spot, untouched, unassigned


def damaged(cur):
    cur.execute(
        """SELECT tp.ID_TPALINSE id, tpa.id_contrattirighe line_id, CONVERT(VARCHAR(10),tp.DATA,101) d,
                  tp.ID_FILMATI, tp.COD_PROGRA, tp.TITLE, tp.NEWTYPE, tp.SUPPORTO, tp.ASPECT, tp.DURATION_P
           FROM trafficPalinse tpa JOIN TPALINSE tp ON tp.ID_TPALINSE = tpa.id_tpalinse
           JOIN CONTRATTIRIGHE cr ON cr.ID_CONTRATTIRIGHE = tpa.id_contrattirighe
           WHERE cr.ID_CONTRATTITESTATA = %s AND tp.ID_FILMATI = %s AND tp.LIVELLO = 0
           ORDER BY tpa.id_contrattirighe, tp.DATA""",
        (CONTRACT, BAD_FILMATI),
    )
    return cur.fetchall()


def oracle(cur, tp_id):
    cur.execute(
        "SELECT ID_FILMATI, COD_PROGRA, TITLE, NEWTYPE, SUPPORTO, ASPECT, DURATION_P"
        " FROM TPALINSE WHERE ID_TPALINSE = %s",
        (tp_id,),
    )
    return cur.fetchone()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    with connect() as conn:
        cur = conn.cursor(as_dict=True)
        rows = damaged(cur)
        o_tm = oracle(cur, ORACLE_TM0701_TP)
        o_un = oracle(cur, ORACLE_UNASSIGNED_TP)
        assert o_tm["ID_FILMATI"] == TM0701, o_tm
        assert o_un["ID_FILMATI"] == -1, o_un
        print(f"damaged rows: {len(rows)} (expect 39)")
        by_line = {}
        for r in rows:
            by_line.setdefault(r["line_id"], []).append(r)
        for lid, rs in by_line.items():
            print(f"  line {lid}: {len(rs)} spots {rs[0]['d']}..{rs[-1]['d']}")
        if len(rows) != 39 or set(by_line) != {LINE_TM0701, *LINES_UNASSIGNED}:
            print("unexpected state — refusing")
            return 2

        # backup of the current (damaged) values so the write can be reverted
        stamp = datetime.now().strftime("%Y%m%d")
        bk = (
            Path(__file__).resolve().parents[1]
            / "logs"
            / f"pechanga-3133-traffic-repair-restore-{stamp}.sql"
        )
        with bk.open("w") as f:
            f.write(
                "-- re-applies the pre-repair (damaged) values; generated by repair_pechanga_3133_traffic.py\n"
            )
            for r in rows:
                dp = "NULL" if r["DURATION_P"] is None else r["DURATION_P"]
                f.write(
                    f"UPDATE TPALINSE SET ID_FILMATI={r['ID_FILMATI']}, COD_PROGRA='{r['COD_PROGRA']}', "
                    f"TITLE='{(r['TITLE'] or '').replace(chr(39), chr(39) * 2)}', NEWTYPE='{r['NEWTYPE']}', "
                    f"SUPPORTO='{r['SUPPORTO']}', ASPECT='{r['ASPECT']}', DURATION_P={dp} WHERE ID_TPALINSE={r['id']};\n"
                )
            for pid, lid in zip(POOL_ROWS, (84747, 84746, 84748, 84749)):
                f.write(
                    f"INSERT INTO CONTRATTIFILMATI (ID_CONTRATTIRIGHE, ID_FILMATI, PERCROTATION) VALUES ({lid}, {BAD_FILMATI}, 0); -- was id {pid}\n"
                )
        print(f"backup: {bk}")

        n_tm = n_un = 0
        for r in rows:
            if r["line_id"] == LINE_TM0701:
                vals = o_tm
                title = o_tm["TITLE"]
            else:
                vals = o_un
                title = LINES_UNASSIGNED[r["line_id"]]
            cur.execute(
                "UPDATE TPALINSE SET ID_FILMATI=%s, COD_PROGRA=%s, TITLE=%s, NEWTYPE=%s, SUPPORTO=%s, ASPECT=%s, DURATION_P=%s"
                " WHERE ID_TPALINSE=%s AND ID_FILMATI=%s",
                (
                    vals["ID_FILMATI"],
                    vals["COD_PROGRA"],
                    title,
                    vals["NEWTYPE"],
                    vals["SUPPORTO"],
                    vals["ASPECT"],
                    vals["DURATION_P"],
                    r["id"],
                    BAD_FILMATI,
                ),
            )
            assert cur.rowcount == 1, r
            if r["line_id"] == LINE_TM0701:
                n_tm += 1
            else:
                n_un += 1
        cur.execute(
            f"DELETE FROM CONTRATTIFILMATI WHERE ID_CONTRATTIFILMATI IN ({','.join(map(str, POOL_ROWS))})"
            f" AND ID_FILMATI = %s AND ID_CONTRATTIRIGHE IN (84746,84747,84748,84749)",
            (BAD_FILMATI,),
        )
        n_pool = cur.rowcount
        print(
            f"in txn: {n_tm} -> TM0701 (146119), {n_un} -> unassigned, {n_pool} pool rows removed"
        )

        # in-transaction readback
        cur.execute(
            """SELECT tpa.id_contrattirighe line_id, tp.ID_FILMATI, COUNT(*) n
               FROM trafficPalinse tpa JOIN TPALINSE tp ON tp.ID_TPALINSE = tpa.id_tpalinse
               JOIN CONTRATTIRIGHE cr ON cr.ID_CONTRATTIRIGHE = tpa.id_contrattirighe
               WHERE cr.ID_CONTRATTITESTATA = %s AND tp.LIVELLO = 0
               GROUP BY tpa.id_contrattirighe, tp.ID_FILMATI ORDER BY 1, 2""",
            (CONTRACT,),
        )
        after = cur.fetchall()
        for r in after:
            print("   after:", r)
        ok = (n_tm, n_un, n_pool) == (9, 30, 4) and not any(
            r["ID_FILMATI"] == BAD_FILMATI for r in after
        )
        if not (ok and args.apply):
            conn.rollback()
            print(
                "ROLLED BACK"
                + ("" if ok else " (verify failed)")
                + ("" if args.apply else " (dry run; pass --apply)")
            )
            return 0 if ok else 1
        conn.commit()
        print("COMMITTED")

    # verify from a fresh connection (lesson 9/23: a script's own print is not evidence)
    with connect() as conn2:
        cur = conn2.cursor(as_dict=True)
        left = damaged(cur)
        cur.execute(
            "SELECT COUNT(*) n FROM CONTRATTIFILMATI WHERE ID_FILMATI=%s AND ID_CONTRATTIRIGHE IN (84746,84747,84748,84749)",
            (BAD_FILMATI,),
        )
        pool_left = cur.fetchone()["n"]
        cur.execute(
            "SELECT COUNT(*) n FROM trafficPalinse tpa JOIN TPALINSE tp ON tp.ID_TPALINSE=tpa.id_tpalinse WHERE tpa.id_contrattirighe=%s AND tp.ID_FILMATI=%s AND tp.LIVELLO=0",
            (LINE_TM0701, TM0701),
        )
        tm_now = cur.fetchone()["n"]
        print(
            f"fresh connection: 148842 rows left={len(left)} pool rows left={pool_left} 84746 spots on TM0701={tm_now} (expect 0 / 0 / 12)"
        )
        return 0 if (not left and pool_left == 0 and tm_now == 12) else 1


if __name__ == "__main__":
    sys.exit(main())
